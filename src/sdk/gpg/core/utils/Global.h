namespace gpg
{
	using die_handler_t = void (*)(const char*);
	using mem_hook_t = void (*)(int, int, ...);

	struct HeapStats
	{
		std::uint32_t reserved;      // +0x00
		std::uint32_t committed;     // +0x04
		std::uint32_t total;         // +0x08
		std::uint32_t inSmallBlocks; // +0x0C
		std::uint32_t inUse;         // +0x10
	};
	static_assert(offsetof(HeapStats, reserved) == 0x00, "gpg::HeapStats::reserved offset must be 0x00");
	static_assert(offsetof(HeapStats, committed) == 0x04, "gpg::HeapStats::committed offset must be 0x04");
	static_assert(offsetof(HeapStats, total) == 0x08, "gpg::HeapStats::total offset must be 0x08");
	static_assert(offsetof(HeapStats, inSmallBlocks) == 0x0C, "gpg::HeapStats::inSmallBlocks offset must be 0x0C");
	static_assert(offsetof(HeapStats, inUse) == 0x10, "gpg::HeapStats::inUse offset must be 0x10");
	static_assert(sizeof(HeapStats) == 0x14, "gpg::HeapStats size must be 0x14");

	void HandleAssertFailure(const char* msg, int lineNum, const char* file); // 0x0093EDE0

	/**
	 * Address: 0x00938FE0 (FUN_00938FE0, gpg::SetDieHandler)
	 * Mangled: ?SetDieHandler@gpg@@YAP6AXPBD@ZP6AX0@Z@Z
	 *
	 * What it does:
	 * Installs one process-global fatal-error callback and returns the previous
	 * callback pointer.
	 */
	die_handler_t SetDieHandler(die_handler_t handler);

	/**
	 * Address: 0x00938FF0 (FUN_00938FF0, gpg::InvokeDieHandler)
	 * Mangled: ?InvokeDieHandler@gpg@@YAXPBD@Z
	 *
	 * What it does:
	 * Dispatches one message to the current process-global die handler when set.
	 */
	void InvokeDieHandler(const char*);

	/**
	 * Address: 0x00939000 (FUN_00939000, gpg::Die)
	 *
	 * What it does:
	 * Formats the message, hands it to the die handler and never returns.
	 * Every call site in the binary ends at the call, with no code after it.
	 */
	[[noreturn]] void Die(const char* args, ...);

	/**
	 * Address: 0x00957EF0 (FUN_00957EF0, func_SetMemHook)
	 *
	 * What it does:
	 * Installs or clears the process-wide memory hook callback pointer.
	 */
	void SetMemHook(mem_hook_t hook);

	mem_hook_t GetMemHook();

	/**
	 * Address: 0x00958D60 (FUN_00958D60, func_GetHeapInfo)
	 *
	 * What it does:
	 * Copies allocator heap counters into `outStats` under allocator lock.
	 */
	void GetHeapInfo(HeapStats* outStats);

#if defined(_M_X64)
	/**
	 * x64 port test mode (not in the binary): logs what `FAF_HIGHMEM=1` reserved
	 * below 4 GB before the CRT started, or why it was skipped. No-op when the
	 * mode was not requested.
	 */
	void LogHighMemoryReservation();
#endif

	/**
	 * Address: 0x008D8FA0 (FUN_008D8FA0, func_ParseNum)
	 *
	 * What it does:
	 * Parses one signed integer from `[start,end)` using legacy base autodetect
	 * rules (`0x` hex, leading `0` octal, otherwise decimal).
	 */
	bool ParseNum(const char* start, const char* end, int* dest) noexcept;

	/**
	 * Address: 0x009071D0 (FUN_009071D0, gpg::SetThreadName)
	 *
	 * What it does:
	 * Emits the MSVC debugger thread-name exception payload for `id`/`name`
	 * when AQtime instrumentation mode allows it.
	 */
	void SetThreadName(unsigned int id, const char* name);
}

