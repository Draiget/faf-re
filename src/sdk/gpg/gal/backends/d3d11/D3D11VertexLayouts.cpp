    struct LayoutTable
    {
      const D3D11_INPUT_ELEMENT_DESC* elements;
      std::uint32_t count;
    };

    template <std::size_t N>
    constexpr LayoutTable Table(const D3D11_INPUT_ELEMENT_DESC (&elements)[N]) noexcept
    {
      return LayoutTable{elements, static_cast<std::uint32_t>(N)};
    }

