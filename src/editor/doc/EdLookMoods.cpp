  const LookMood* FindLookMood(
    const std::string& id
  )
  {
    for (const LookMood& mood : LookMoods()) {
      if (id == mood.id) {
        return &mood;
      }
    }
    return nullptr;
  }

  LightingState MoodLighting(
    const LookMood& mood,
    const LightingState& base
  )
  {
    LightingState out = base;
    SunDirectionOf(mood.azimuth, mood.elevation, out.sunDirection);
    out.multiplier = mood.multiplier;
    for (int c = 0; c < 3; ++c) {
      out.sunColor[c] = mood.sun[c];
      out.sunAmbience[c] = mood.ambience[c];
      out.shadowFill[c] = mood.shadow[c];
      out.fogColor[c] = mood.fog[c];
    }
    out.fogStart = mood.fogStart;
    out.fogEnd = mood.fogEnd;
    out.bloom = mood.bloom;
    return out;
  }
