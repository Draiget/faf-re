#!/usr/bin/env python3
"""Writes tools/mapformat/DUMP_NAMES.md: the dump rules as implemented and every field name the spec does not give.

    python tools/mapformat/gen_dump_names.py          (rewrites DUMP_NAMES.md)
    python tools/mapformat/gen_dump_names.py --check  (exit 1 when the file is out of date)

The table is generated from the `note=` marks in the chunk schemas, so it cannot drift from the code.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from mapfmt import chunks as C                                 # noqa: E402,F401
from mapfmt import chunks_world3d                              # noqa: E402
from mapfmt.chunkdef import CHUNKS                             # noqa: E402
from mapfmt.schema import Array, Rep, Struct                   # noqa: E402

PATH = os.path.join(HERE, "DUMP_NAMES.md")

HEAD = """# Dump names and rules (reference implementation)

`mapinfo.py --dump` / `dump_text()` is the conformance output of CONTAINER.md section 8. The C++ `DumpText` must match
it byte for byte. This file lists (1) the rules as implemented where the spec leaves room, (2) every field name the
spec does not give, chosen by the reference. It is generated by `gen_dump_names.py`; do not edit by hand.

## Rules as implemented

* Lines end with `\\n`, the output is ASCII, the last line ends with `\\n`.
* File lines, in this order: `file.container`, `file.revision`, `file.flags` (`0x` + 8 hex digits, the header flags),
  `file.required`, `file.optional` (`0x` + 16 hex digits), `file.mapGuid` (32 hex), `file.simHash` (64 hex).
* Then one block per directory entry, in directory order. Header: `chunk ID inst=N ver=V flags=0xFFFF raw=N` (the
  *stored* directory flags, DEFLATE bit included; `raw` = declared raw size). An unknown chunk id, a chunk of a
  container-4-only id inside a container-3 file, or a version newer than the reader knows is printed as
  `chunk ID inst=N skipped` and nothing else (it can only be optional, a required one refuses the file).
* Fields: `ID.field = value`, names exactly as in the spec (camelCase). Nested struct: `ID.parent.child`.
  Array of structs: `ID.arr.count = n`, then `ID.arr[i].field`; array of scalars `ID.arr[i] = v`. An array whose
  count is not stored (`Rep`: SPLT `planes`, INST `materialOverride`, LITE `sh`, COLL `vertices`/`indices`/
  `triangleSurfaces`, NAVS `indices`) is dumped the same way, with its `.count` line.
* Integers: decimal. `f32:` + 8 hex digits of the bit pattern; `f64:` + 16 hex digits.
* Fixed point (fx8/fx10/fx16/fx32) and raw binary16 (`f16`, `u16` holding a half) are dumped as the raw integer.
* Enums and flags: the integer. Booleans (`u8`): the integer.
* Strings and paths: JSON string, ASCII only: `"` `\\\\` and `\\b \\f \\n \\r \\t` escaped, other control characters below 0x20
  as `\\u00xx`, everything from 0x7f up as `\\uxxxx` per UTF-16 code unit (lower case hex, surrogate pairs for
  non-BMP). That is Python's `json.dumps(s, ensure_ascii=True)`; note it leaves 0x7f unescaped.
* Fixed-size vectors inline: `[a, b, c]` (vec2/3/4, quat, color3, `srgb8`, fxvec2, fx10vec3, `f32[N]`, `i16[4]`,
  `u16[3]`, ...). `OCCL.portals[i].quad` (`vec3[4]`) is the 12 floats flattened into one inline list.
* Byte blobs, fixed byte arrays (`u8[32] publicKey`, `inputHash`, ...) and bitmasks:
  `bytes[n] sha256:<hex>` over the stored bytes (bitmask: all rows, padding bits as stored).
* A blob that has a stored count prints the count first as its own line, named as in the spec
  (`byteCount`, `jsonLen`, `size`, `dirByteCount`), then the blob under the data name.
* Planes: `plane[COLSxROWS] sha256:<hex>` over the **decoded** little-endian samples (predictor reversed). COLS x ROWS
  are the plane's columns and rows; for interleaved planes (SPLT mode 0, WFLW) the channels are not part of the
  brackets. The plane's own `u8 predictor` (the unnamed one in `plane<T>`) is **not** dumped; the named `predictor`
  fields of HGHT and HDET are.
* Conditional fields (spec "when ...") are printed only when present, in spec order.

## Chosen names

Fields the spec describes without giving a name (`array<loc>`, the bytes after a count, ...). Columns: chunk,
path of the field inside the chunk (`[]` = array element), name the dump uses, the spec text it stands for.

| Chunk | Field path | Name | Spec phrase |
|---|---|---|---|
"""


def walk(ty, path, cid, rows):
    if isinstance(ty, Struct):
        for f in ty.fields:
            p = path + [f.name]
            if f.note:
                rows.append((cid, ".".join(p).replace(".[", "["), f.name, f.note))
            walk(f.ty, p, cid, rows)
    elif isinstance(ty, (Array, Rep)):
        walk(ty.elem, path[:-1] + [path[-1] + "[]"], cid, rows)


def render():
    rows = []
    for cid, cd in CHUNKS.items():
        walk(cd.schema, [], cid, rows)
    walk(chunks_world3d.NATIVE_MESH, [], "MSHB (format 1 body)", rows)
    seen, lines = set(), []
    for r in rows:
        if r in seen:
            continue
        seen.add(r)
        lines.append("| %s | `%s` | `%s` | %s |" % (r[0], r[1], r[2], r[3]))
    return HEAD + "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        # Line endings are not content: a checkout with autocrlf has CRLF.
        ok = os.path.exists(PATH) and open(PATH, encoding="utf-8", newline="").read().replace("\r\n", "\n") == text
        print("DUMP_NAMES.md is up to date" if ok else "DUMP_NAMES.md is out of date")
        return 0 if ok else 1
    with open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
