"""Generates src/editor/doc/EdLuaApiTable.inc: the functions a map script can call, for the Script Editor's completions,
signatures and hover (doc/EdLuaApi.cpp).

Sources:
  * FAF's annotated engine Lua (FAForever/fa, engine/Core.lua, Sim.lua, Library.lua and engine/Sim/*.lua) at one commit,
    fetched into a folder (`--engine <folder containing engine/>`, `--commit <sha>` names it in the output);
  * the scenario libraries map scripts import, from the game's lua.nx2 (`--lua <path to lua.nx2>`):
    /lua/sim/ScenarioUtilities.lua as ScenarioUtils, /lua/ScenarioFramework.lua as ScenarioFramework.

Each `function Name(args)` / `function Class:Method(args)` with the `---` comment block above it gives one entry:
owner (the class or module, empty for globals), name, the parameters with their types, the return type and the
description.

Usage: python tools/editor/gen_lua_api.py --engine <dir> --commit <sha> --lua <lua.nx2> --out src/editor/doc/EdLuaApiTable.inc
"""
import argparse
import pathlib
import re
import zipfile

FUNCTION = re.compile(r'^function\s+([A-Za-z_][\w]*)(?:([.:])([A-Za-z_]\w*))?\s*\(([^)]*)\)')
PARAM = re.compile(r'^---@param\s+([\w.]+)\??\s+(\S+)(?:\s+(.*))?$')
RETURN = re.compile(r'^---@return\s+(\S+)')


def parse(text, owner_of_module=None):
    """Entries from one Lua file's text."""
    entries = []
    block = []
    for raw in text.splitlines():
        line = raw.rstrip()
        if line.startswith('---'):
            block.append(line)
            continue
        match = FUNCTION.match(line)
        if match:
            head, sep, tail, args = match.groups()
            if sep:
                owner, name = head, tail
            else:
                owner, name = (owner_of_module or ''), head
            types = {}
            notes = []
            returns = ''
            for item in block:
                param = PARAM.match(item)
                ret = RETURN.match(item)
                if param:
                    types[param.group(1)] = param.group(2)
                elif ret:
                    returns = ret.group(1) if not returns else returns + ', ' + ret.group(1)
                elif not item.startswith('---@'):
                    note = item[3:].strip()
                    if note:
                        notes.append(note)
            params = []
            for arg in [a.strip() for a in args.split(',') if a.strip()]:
                params.append(f'{arg}: {types[arg]}' if arg in types else arg)
            # Module functions without annotations still count; private helpers (leading underscore) don't.
            if not name.startswith('_'):
                entries.append((owner, name, ', '.join(params), returns, ' '.join(notes)))
        block = []
    return entries


def escape(text):
    return text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--engine', required=True)
    parser.add_argument('--commit', required=True)
    parser.add_argument('--lua', required=True)
    parser.add_argument('--out', required=True)
    args = parser.parse_args()

    engine = pathlib.Path(args.engine) / 'engine'
    files = [engine / 'Core.lua', engine / 'Sim.lua', engine / 'Library.lua'] + sorted((engine / 'Sim').glob('*.lua'))
    entries = []
    for file in files:
        entries += parse(file.read_text(encoding='utf-8', errors='replace'))
    with zipfile.ZipFile(args.lua) as archive:
        for path, alias in (('lua/sim/ScenarioUtilities.lua', 'ScenarioUtils'),
                            ('lua/ScenarioFramework.lua', 'ScenarioFramework')):
            name = next(n for n in archive.namelist() if n.lower() == path.lower())
            entries += parse(archive.read(name).decode('utf-8', errors='replace'), alias)

    # One entry per owner and name (the first wins), sorted for lookups.
    seen = set()
    unique = []
    for entry in entries:
        key = (entry[0], entry[1])
        if key not in seen:
            seen.add(key)
            unique.append(entry)
    unique.sort(key=lambda e: (e[0].lower(), e[1].lower()))

    lines = [
        '// Generated by tools/editor/gen_lua_api.py: do not edit.',
        f'// FAForever/fa engine annotations at commit {args.commit} (engine/Core.lua, Sim.lua, Library.lua, Sim/*.lua),',
        '// and the game\'s /lua/sim/ScenarioUtilities.lua (ScenarioUtils) and /lua/ScenarioFramework.lua.',
        f'// {len(unique)} functions: owner, name, parameters, returns, description.',
    ]
    for owner, name, params, returns, doc in unique:
        lines.append(f'{{"{escape(owner)}", "{escape(name)}", "{escape(params)}", "{escape(returns)}", "{escape(doc)}"}},')
    pathlib.Path(args.out).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(len(unique), 'functions into', args.out)


if __name__ == '__main__':
    main()
