"""Writes src/platform/posix/NtfsUpcaseTable.inc: Windows' upper-case table for the BMP, the table
NTFS compares names by ($UpCase), as the POSIX file calls (src/platform/posix/Win32Shim.cpp) need it
to find a name the way Windows finds it. Run on Windows:

    python tools/linux/ntfs_upcase_table.py src/platform/posix/NtfsUpcaseTable.inc

It asks ntdll's RtlUpcaseUnicodeChar for every code point from U+0080 to U+FFFF (ASCII is folded in
code) and keeps those whose upper case differs.
"""
import ctypes
import sys


def main(out_path):
    ntdll = ctypes.WinDLL("ntdll")
    ntdll.RtlUpcaseUnicodeChar.restype = ctypes.c_wchar
    ntdll.RtlUpcaseUnicodeChar.argtypes = [ctypes.c_wchar]
    pairs = []
    for c in range(0x80, 0x10000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        upper = ord(ntdll.RtlUpcaseUnicodeChar(chr(c)))
        if upper != c:
            pairs.append((c, upper))
    lines = [
        "// Generated by tools/linux/ntfs_upcase_table.py from Windows' RtlUpcaseUnicodeChar: every BMP",
        "// letter from U+0080 whose upper case differs, as {letter, upper case}, sorted by letter. Don't edit.",
    ]
    for at in range(0, len(pairs), 6):
        lines.append(" ".join(f"{{0x{c:04X}u, 0x{u:04X}u}}," for c, u in pairs[at:at + 6]))
    with open(out_path, "w", encoding="ascii", newline="\n") as out:
        out.write("\n".join(lines) + "\n")
    print(f"{len(pairs)} pairs -> {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: ntfs_upcase_table.py <output .inc>")
    main(sys.argv[1])
